import CoreLocation
import FirebaseFirestore
import Foundation
import OSLog
import RealmSwift

/// Represents the `Collaboration` (`projects/collaboration` path in Firestore)
///
/// Encoded as:
///
///     {
///         "feature"    : "e5db7eb2-bd9f-44ba-9c90-e6e6e528b930",
///         "statusName" : "6403e6dd-52df-4f4b-bf06-167e53b27e7a",
///         "name"       : "name",
///         "description": "description"
///         "tags"       : // not implemented on iOS yet
///     }
struct FirestoreCollaboration: Decodable, FirestoreToRealmSyncable {
    typealias ModelType = Collaboration

    /// CodingKeys used by Codable as a keys in the encoded form
    enum CodingKeys: String, CodingKey, CaseIterable {
        case assigneeId = "assignee",
             categoryId,
             createdById = "createdBy",
             createdAt,
             descriptionString = "description",
             dueDateTimestamp,
             followers,
             geometryId,
             identifier,
             lastUpdatedAt,
             name,
             statusId = "statusName",
             tagIds = "tags"
    }

    var assigneeId: String?
    var categoryId: String?
    var createdById: String?
    var createdAt: Date
    var descriptionString: String?
    var dueDateTimestamp: Date?
    var geometryId: String
    var followers: [String]?
    /// identifier "1"... autogenerated, to be displayed in the UI
    var identifier: String?
    var lastUpdatedAt: Date
    var name: String
    var statusId: String?
    var tagIds: [String]

    func upsert(withId id: String, inRealm realm: Realm) throws {
        if let existingCollaboration = realm.object(ofType: Collaboration.self, forPrimaryKey: id) {
            existingCollaboration.cleanupOldTags(newTagIds: tagIds)
        }

        let geometry = realm.objectOrPlaceholder(ofType: Geometry.self, forPrimaryKey: geometryId)
        let collaboration = Collaboration(
            id: id,
            createdAt: createdAt,
            lastUpdatedAt: lastUpdatedAt,
            name: name,
            description: descriptionString,
            dueDateTimestamp: dueDateTimestamp,
            identifier: identifier
        )
        if let categoryId {
            collaboration.category = realm.objectOrPlaceholder(ofType: Category.self, forPrimaryKey: categoryId)
        }
        if let createdById {
            collaboration.author = realm.objectOrPlaceholder(ofType: Participant.self, forPrimaryKey: createdById)
        }
        if let statusId {
            collaboration.status = realm.objectOrPlaceholder(ofType: Status.self, forPrimaryKey: statusId)
        }
        if let assigneeId {
            collaboration.assignee = realm.objectOrPlaceholder(ofType: Participant.self, forPrimaryKey: assigneeId)
        }
        realm.add(collaboration, update: .modified)
        collaboration.tags.removeAll()
        collaboration.addNewTags(newTagIds: tagIds, realm: realm)
        collaboration.followers.removeAll()
        collaboration.addNewFollowers(newFollowerIds: followers ?? [], realm: realm)
        geometry.collaborations.insert(collaboration)
    }
}
